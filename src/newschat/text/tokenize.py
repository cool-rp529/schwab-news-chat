# Words whose trailing "s" is not a plural marker.
_NO_STEM = frozenset({"news", "business", "analysis", "series", "sales", "class", "loss", "plus"})

_TOKEN_RE = re.compile(r"\$?[a-z0-9]+(?:\.[0-9]+)?")
_CLITIC_RE = re.compile(r"[’'`](?:s|d|ll|re|ve|m)\b")


def stem(token: str) -> str:
    if token.startswith("$") or token[0].isdigit() or token in _NO_STEM:
        return token
    if len(token) > 4 and token.endswith("ies"):
        return token[:-3] + "y"
    if len(token) > 5 and token.endswith("ing"):
        return token[:-3]
    if len(token) > 4 and token.endswith("ed"):
        return token[:-2]
    if len(token) > 3 and token.endswith("s") and not token.endswith(("ss", "us", "is")):
        return token[:-1]
    return token


def tokenize(text: str) -> list[str]:
    lowered = _CLITIC_RE.sub("", text.lower())
    return [stem(t) for t in _TOKEN_RE.findall(lowered) if t not in STOPWORDS]
